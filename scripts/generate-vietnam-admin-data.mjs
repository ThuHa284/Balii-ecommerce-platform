import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';

const SOURCE_COMMIT = 'd10fd83c4bf7a5839a56706f1c04f13133271cfc';
const SOURCE_URL =
  `https://raw.githubusercontent.com/thanglequoc/vietnamese-provinces-database/${SOURCE_COMMIT}` +
  '/json/vn_only_simplified_json_generated_data_vn_units_minified.json';
const EXPECTED_PROVINCES = 34;
const EXPECTED_WARDS = 3321;

const inputPath = process.argv[2] ? resolve(process.argv[2]) : null;
const outputPath = process.argv[3]
  ? resolve(process.argv[3])
  : resolve(
      'libs/database/src/migrations/data/vietnam-administrative-units.ts',
    );

const raw = inputPath
  ? await readFile(inputPath, 'utf8')
  : await fetch(SOURCE_URL).then(async (response) => {
      if (!response.ok) {
        throw new Error(
          `Không tải được dữ liệu nguồn: HTTP ${response.status}.`,
        );
      }
      return response.text();
    });
const provinces = JSON.parse(raw);
const wards = provinces.flatMap((province) =>
  province.Wards.map((ward) => [
    String(ward.Code),
    String(province.Code),
    String(ward.FullName),
  ]),
);

if (
  provinces.length !== EXPECTED_PROVINCES ||
  wards.length !== EXPECTED_WARDS
) {
  throw new Error(
    `Dữ liệu không đúng kỳ vọng: ${provinces.length} tỉnh/thành, ${wards.length} phường/xã.`,
  );
}

const wardCodes = new Set();
for (const [code] of wards) {
  if (wardCodes.has(code)) {
    throw new Error(`Dữ liệu có mã phường/xã ${code} bị trùng.`);
  }
  wardCodes.add(code);
}
const sha256 = createHash('sha256').update(raw).digest('hex');
const provinceRows = provinces.map((province) => [
  String(province.Code),
  String(province.FullName),
]);
const output = `// Generated by scripts/generate-vietnam-admin-data.mjs.
// Source: ${SOURCE_URL}
// SHA-256: ${sha256}
// Snapshot: 34 tỉnh/thành và 3.321 phường/xã, cập nhật đến 18/07/2026.

export const VIETNAM_PROVINCES: ReadonlyArray<readonly [string, string]> = ${JSON.stringify(provinceRows, null, 2)};

export const VIETNAM_WARDS: ReadonlyArray<readonly [string, string, string]> = ${JSON.stringify(wards, null, 2)};
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, output, 'utf8');

console.log(
  `Đã tạo ${outputPath} (${provinceRows.length} tỉnh/thành, ${wards.length} phường/xã, SHA-256 ${sha256}).`,
);
